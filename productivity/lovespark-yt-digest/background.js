'use strict';

// ── Constants ─────────────────────────────────────────────────────
const DEFAULTS = {
  isEnabled: true,
  apiKey: '',
  model: 'gpt-4o-mini',
  summaryStyle: 'bullets',
  summaryLength: 'medium',
  cacheDurationDays: 7,
  digestsToday: 0,
  digestsTotal: 0,
  lastResetDate: '',
  theme: 'retro',
};

const LENGTH_WORDS = { short: 200, medium: 500, long: 1000 };

const STYLE_INSTRUCTIONS = {
  bullets: 'Use bullet points with bold key terms. Be concise and scannable.',
  paragraph: 'Write in flowing paragraphs. Use bold for key terms.',
  technical: 'Focus on technical details, code patterns, and implementation specifics. Use bullet points.',
};

const OPENAI_URL = 'https://api.openai.com/v1/chat/completions';
const MAX_TRANSCRIPT_CHARS = 100_000;
const CHUNK_CHARS = 40_000;

// ── In-memory cache ───────────────────────────────────────────────
const captionCache = new Map();
const summaryCache = new Map();
const MEMORY_TTL = 3_600_000;

// ── Initialize defaults ───────────────────────────────────────────
chrome.runtime.onInstalled.addListener(() => {
  chrome.storage.local.get(null, (data) => {
    const toSet = {};
    for (const [key, val] of Object.entries(DEFAULTS)) {
      if (data[key] === undefined) toSet[key] = val;
    }
    if (Object.keys(toSet).length) chrome.storage.local.set(toSet);
  });
  purgeExpiredCache();
});

chrome.runtime.onStartup.addListener(() => {
  purgeExpiredCache();
});

// ── Daily reset ───────────────────────────────────────────────────
function todayStr() {
  return new Date().toISOString().slice(0, 10);
}

function checkDailyReset(callback) {
  chrome.storage.local.get(['lastResetDate', 'digestsToday'], (data) => {
    const today = todayStr();
    if (data.lastResetDate !== today) {
      chrome.storage.local.set({ lastResetDate: today, digestsToday: 0 }, () => {
        if (callback) callback(0);
      });
    } else {
      if (callback) callback(data.digestsToday || 0);
    }
  });
}

// ── Badge ─────────────────────────────────────────────────────────
function updateBadge(count) {
  const text = count > 0 ? String(count) : '';
  chrome.action.setBadgeText({ text });
  chrome.action.setBadgeBackgroundColor({ color: '#FF69B4' });
}

// ── Cache purge ───────────────────────────────────────────────────
function purgeExpiredCache() {
  chrome.storage.local.get(null, (data) => {
    const days = data.cacheDurationDays || 7;
    const cutoff = Date.now() - days * 86_400_000;
    const toRemove = [];
    for (const key of Object.keys(data)) {
      if (key.startsWith('digest_') && data[key]?.cachedAt < cutoff) {
        toRemove.push(key);
      }
    }
    if (toRemove.length) chrome.storage.local.remove(toRemove);
  });
}

// ── Transcript fetch + parse ──────────────────────────────────────
async function fetchTranscript(tracks) {
  const sorted = [...tracks].sort((a, b) => {
    if (a.kind === 'asr' && b.kind !== 'asr') return 1;
    if (a.kind !== 'asr' && b.kind === 'asr') return -1;
    if (a.languageCode === 'en' && b.languageCode !== 'en') return -1;
    if (a.languageCode !== 'en' && b.languageCode === 'en') return 1;
    return 0;
  });

  const track = sorted[0];
  if (!track?.baseUrl) throw new Error('No caption track URL available');

  const isAuto = track.kind === 'asr';
  const resp = await fetch(track.baseUrl);
  if (!resp.ok) throw new Error('Failed to fetch transcript: ' + resp.status);

  const xml = await resp.text();
  const segments = parseTranscriptXml(xml);
  return { segments, isAutoGenerated: isAuto, language: track.languageCode };
}

function parseTranscriptXml(xml) {
  const segments = [];
  const regex = /<text\s+start="([^"]*)"(?:\s+dur="([^"]*)")?[^>]*>([\s\S]*?)<\/text>/g;
  let match;
  while ((match = regex.exec(xml)) !== null) {
    const start = parseFloat(match[1]) || 0;
    const dur = parseFloat(match[2]) || 0;
    let text = match[3]
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&quot;/g, '"')
      .replace(/&#39;/g, "'")
      .replace(/<[^>]+>/g, '')
      .trim();
    if (text) segments.push({ start, dur, text });
  }
  return segments;
}

function segmentsToText(segments) {
  return segments.map(s => s.text).join(' ');
}

function segmentsToTimestamped(segments) {
  return segments.map(s => {
    const m = Math.floor(s.start / 60);
    const sec = Math.floor(s.start % 60);
    const ts = m + ':' + String(sec).padStart(2, '0');
    return '[' + ts + '] ' + s.text;
  }).join('\n');
}

// ── OpenAI API ────────────────────────────────────────────────────
function buildSystemPrompt(style, length) {
  const wordCount = LENGTH_WORDS[length] || 500;
  const styleNote = STYLE_INSTRUCTIONS[style] || STYLE_INSTRUCTIONS.bullets;
  return 'You summarize YouTube videos for a neurodivergent user who needs clear, scannable content to decide if a video is worth watching.\n\n' +
    styleNote + '\n\n' +
    'Format your response exactly like this:\n\n' +
    '## Key Points\n' +
    '- 3-7 bullet points with the most important takeaways\n' +
    '- **Bold** key terms and concepts\n\n' +
    '## Summary\n' +
    'A detailed summary (~' + wordCount + ' words). ' + styleNote + '\n\n' +
    '## Worth Watching?\n' +
    'One sentence verdict: who should watch this and why (or why not).';
}

async function callOpenAI(apiKey, model, systemPrompt, transcript, videoTitle, videoAuthor) {
  const userMsg = 'Video: "' + videoTitle + '" by ' + (videoAuthor || 'unknown creator') + '\n\nTranscript:\n' + transcript;

  const resp = await fetch(OPENAI_URL, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': 'Bearer ' + apiKey,
    },
    body: JSON.stringify({
      model,
      messages: [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: userMsg },
      ],
      temperature: 0.3,
      max_tokens: 2000,
    }),
  });

  if (!resp.ok) {
    const err = await resp.json().catch(() => ({}));
    if (resp.status === 429) {
      const retryAfter = resp.headers.get('retry-after');
      throw new Error('Rate limited. ' + (retryAfter ? 'Retry after ' + retryAfter + 's.' : 'Please wait a moment.'));
    }
    if (resp.status === 401) {
      throw new Error('Invalid API key. Check your key in Settings.');
    }
    throw new Error(err?.error?.message || 'OpenAI API error: ' + resp.status);
  }

  const json = await resp.json();
  return json.choices?.[0]?.message?.content || '';
}

async function summarizeTranscript(videoId, apiKey, model, style, length, tracks, videoDetails) {
  const { segments, isAutoGenerated, language } = await fetchTranscript(tracks);
  const plainText = segmentsToText(segments);
  const timestamped = segmentsToTimestamped(segments);
  const systemPrompt = buildSystemPrompt(style, length);

  let summary;
  if (plainText.length > MAX_TRANSCRIPT_CHARS) {
    summary = await summarizeLongTranscript(apiKey, model, systemPrompt, plainText, videoDetails);
  } else {
    summary = await callOpenAI(apiKey, model, systemPrompt, plainText, videoDetails?.title || 'Unknown Video', videoDetails?.author || '');
  }

  if (isAutoGenerated) {
    summary = '> *Note: This summary is based on auto-generated captions, which may contain inaccuracies.*\n\n' + summary;
  }

  return { summary, transcript: timestamped, segments, language, isAutoGenerated };
}

async function summarizeLongTranscript(apiKey, model, systemPrompt, plainText, videoDetails) {
  const chunks = [];
  for (let i = 0; i < plainText.length; i += CHUNK_CHARS) {
    chunks.push(plainText.slice(i, i + CHUNK_CHARS));
  }

  const title = videoDetails?.title || 'Unknown Video';
  const author = videoDetails?.author || '';
  const chunkSummaries = [];

  for (let i = 0; i < chunks.length; i++) {
    const chunkPrompt = 'Summarize this section (part ' + (i + 1) + ' of ' + chunks.length + ') of the video transcript. Focus on key points and main ideas. Keep it concise.';
    const result = await callOpenAI(apiKey, model, chunkPrompt, chunks[i], title, author);
    chunkSummaries.push(result);
  }

  const combined = chunkSummaries.join('\n\n---\n\n');
  const finalPrompt = systemPrompt + '\n\nYou are given summaries of different parts of a long video. Combine them into one cohesive summary following the format above.';
  return callOpenAI(apiKey, model, finalPrompt, combined, title, author);
}

// ── Message handler ───────────────────────────────────────────────
chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  switch (msg.action) {

    case 'captionData': {
      const { videoId, tracks, videoDetails } = msg;
      captionCache.set(videoId, { tracks, videoDetails, ts: Date.now() });
      return false;
    }

    case 'videoChanged':
      return false;

    case 'getVideoStatus': {
      const { videoId } = msg;
      if (!videoId) {
        sendResponse({ status: 'no-video' });
        return true;
      }
      const memCached = summaryCache.get(videoId);
      if (memCached && Date.now() - memCached.ts < MEMORY_TTL) {
        sendResponse({ status: 'done', data: memCached });
        return true;
      }
      chrome.storage.local.get('digest_' + videoId, (result) => {
        const stored = result['digest_' + videoId];
        if (stored?.summary) {
          summaryCache.set(videoId, { ...stored, ts: Date.now() });
          sendResponse({ status: 'done', data: stored });
        } else {
          const caps = captionCache.get(videoId);
          sendResponse({
            status: caps ? 'ready' : 'waiting',
            hasCaptions: !!caps,
            videoDetails: caps?.videoDetails || null,
            isLive: caps?.videoDetails?.isLiveContent || false,
          });
        }
      });
      return true;
    }

    case 'summarize': {
      const { videoId } = msg;
      const caps = captionCache.get(videoId);
      if (!caps) {
        sendResponse({ error: 'No captions available for this video.' });
        return true;
      }
      if (caps.videoDetails?.isLiveContent) {
        sendResponse({ error: "Can't summarize live streams." });
        return true;
      }
      try {
        chrome.storage.local.get(['apiKey', 'model', 'summaryStyle', 'summaryLength'], (prefs) => {
          try {
            if (!prefs.apiKey) {
              sendResponse({ error: 'No API key set. Open Settings to add your OpenAI key.' });
              return;
            }
            summarizeTranscript(
              videoId, prefs.apiKey, prefs.model || 'gpt-4o-mini',
              prefs.summaryStyle || 'bullets', prefs.summaryLength || 'medium',
              caps.tracks, caps.videoDetails
            ).then((result) => {
              const cacheData = {
                summary: result.summary,
                transcript: result.transcript,
                language: result.language,
                isAutoGenerated: result.isAutoGenerated,
                videoDetails: caps.videoDetails,
                cachedAt: Date.now(),
              };
              summaryCache.set(videoId, { ...cacheData, ts: Date.now() });
              chrome.storage.local.set({ ['digest_' + videoId]: cacheData });
              checkDailyReset((todayCount) => {
                const newToday = todayCount + 1;
                chrome.storage.local.get(['digestsTotal'], (d) => {
                  const newTotal = (d.digestsTotal || 0) + 1;
                  chrome.storage.local.set({ digestsToday: newToday, digestsTotal: newTotal });
                  updateBadge(newToday);
                });
              });
              sendResponse({ success: true, data: cacheData });
            }).catch((err) => {
              sendResponse({ error: err.message || 'Summarization failed.' });
            });
          } catch (innerErr) {
            sendResponse({ error: innerErr.message || 'Failed to read preferences.' });
          }
        });
      } catch (outerErr) {
        sendResponse({ error: outerErr.message || 'Storage unavailable.' });
      }
      return true;
    }

    case 'getStats': {
      checkDailyReset((todayCount) => {
        chrome.storage.local.get(['digestsTotal', 'isEnabled'], (data) => {
          sendResponse({
            digestsToday: todayCount,
            digestsTotal: data.digestsTotal || 0,
            isEnabled: data.isEnabled !== false,
          });
          updateBadge(todayCount);
        });
      });
      return true;
    }

    case 'setEnabled':
      chrome.storage.local.set({ isEnabled: msg.enabled });
      return false;

    case 'testApiKey': {
      const key = msg.apiKey;
      (async () => {
        try {
          const resp = await fetch(OPENAI_URL, {
            method: 'POST',
            headers: {
              'Content-Type': 'application/json',
              'Authorization': 'Bearer ' + key,
            },
            body: JSON.stringify({
              model: 'gpt-4o-mini',
              messages: [{ role: 'user', content: 'Say "ok"' }],
              max_tokens: 5,
            }),
          });
          if (resp.ok) {
            sendResponse({ valid: true });
          } else {
            const err = await resp.json().catch(() => ({}));
            sendResponse({ valid: false, error: err?.error?.message || 'HTTP ' + resp.status });
          }
        } catch (err) {
          sendResponse({ valid: false, error: err.message });
        }
      })();
      return true;
    }

    case 'clearCache': {
      chrome.storage.local.get(null, (data) => {
        const toRemove = Object.keys(data).filter(k => k.startsWith('digest_'));
        chrome.storage.local.remove(toRemove, () => {
          summaryCache.clear();
          sendResponse({ cleared: toRemove.length });
        });
      });
      return true;
    }

    case 'getCacheStats': {
      chrome.storage.local.get(null, (data) => {
        const cacheKeys = Object.keys(data).filter(k => k.startsWith('digest_'));
        sendResponse({ count: cacheKeys.length });
      });
      return true;
    }
  }
});

// ── Keyboard shortcut ─────────────────────────────────────────────
chrome.commands.onCommand.addListener((command) => {
  if (command === 'summarize-video') {
    chrome.tabs.query({ active: true, currentWindow: true }, ([tab]) => {
      if (!tab?.url?.includes('youtube.com/watch')) return;
      chrome.tabs.sendMessage(tab.id, { action: 'getVideoId' }, (resp) => {
        if (chrome.runtime.lastError || !resp?.videoId) return;
        const videoId = resp.videoId;
        const caps = captionCache.get(videoId);
        if (!caps) return;
        chrome.storage.local.get(['apiKey'], (prefs) => {
          if (!prefs.apiKey) return;
          chrome.runtime.sendMessage({ action: 'summarize', videoId }, (result) => {
            if (result?.success) {
              chrome.tabs.create({ url: chrome.runtime.getURL('digest.html?v=' + videoId) });
            }
          });
        });
      });
    });
  }
});
