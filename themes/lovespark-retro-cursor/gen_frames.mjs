#!/usr/bin/env node
// Pre-render the animated Y2K SVG cursors into short PNG frame loops.
//
//     node gen_frames.mjs              # every pack in cursors/
//     node gen_frames.mjs cyworld-dotti-pointer cyber-butterfly-emoji
//
// Why: Chrome re-rasterizes an animated SVG cursor on every cursor update and keeps
// its SMIL timeline ticking even when the mouse is still, re-checking every element
// that uses it (~30% of a core per visible tab, measured 2026-11-01). Static PNG
// frames cost about as much as a static cursor; content_script.js steps through
// them only while the mouse moves, on the hovered element only.
//
// Each cursor gets its own loop length L (1.2-2.4 s) and every SMIL dur is retimed
// to L / round(L / dur), so the loop is seamless; L is chosen to keep the largest
// speed change small. Frames are rendered at 1x and 2x with Chrome for Testing
// (Playwright, resolved from the monorepo's node_modules). Writes
// cursors/<pack>/frames/<kind>-<i>.png (+ @2x) and cursor_frames.js (frame counts).
// Run after gen_cursors.py whenever an SVG changes.
import fs from "fs";
import os from "os";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.join(HERE, "../../package.json"));
const { chromium } = require("playwright");

const STEP = 0.15; // seconds per frame; content_script.js ticks at the same rate
const LOOPS = [1.2, 1.5, 1.6, 1.8, 2.4];
const ANIMATED = ["default", "pointer"]; // wait gets one static frame; text has no animation

function durations(svg) {
  return [...new Set([...svg.matchAll(/dur="([\d.]+)s"/g)].map((m) => +m[1]))];
}

// Smallest worst-case speed change wins; ties go to the shorter loop (fewer frames).
function pickLoop(durs) {
  let best = null;
  for (const L of LOOPS) {
    const worst = Math.max(...durs.map((d) => Math.abs(L / Math.max(1, Math.round(L / d)) - d) / d));
    if (!best || worst < best.worst - 1e-9) best = { L, worst };
  }
  return best;
}

function retime(svg, L) {
  return svg.replace(/dur="([\d.]+)s"/g, (_, d) => `dur="${(L / Math.max(1, Math.round(L / +d))).toFixed(4)}s"`);
}

const packs = process.argv.slice(2).length
  ? process.argv.slice(2)
  : fs.readdirSync(path.join(HERE, "cursors")).filter((p) => fs.existsSync(path.join(HERE, "cursors", p, "default.svg"))).sort();

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "lsc-frames-"));
const browser = await chromium.launch({ channel: "chromium", headless: true });
const pages = {};
for (const scale of [1, 2]) {
  pages[scale] = await browser.newPage({ viewport: { width: 32, height: 32 }, deviceScaleFactor: scale });
}

const countsFile = path.join(HERE, "cursor_frames.js");
const counts = {};
if (fs.existsSync(countsFile)) {
  const m = fs.readFileSync(countsFile, "utf8").match(/= (\{[\s\S]*\});/);
  if (m) Object.assign(counts, JSON.parse(m[1]));
}
// Drop packs whose folder is gone, so removed packs leave cursor_frames.js too.
for (const pack of Object.keys(counts)) {
  if (!fs.existsSync(path.join(HERE, "cursors", pack, "default.svg"))) delete counts[pack];
}

for (const pack of packs) {
  const outDir = path.join(HERE, "cursors", pack, "frames");
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  counts[pack] = {};
  for (const kind of [...ANIMATED, "wait"]) {
    const src = fs.readFileSync(path.join(HERE, "cursors", pack, `${kind}.svg`), "utf8");
    const durs = durations(src);
    const animated = ANIMATED.includes(kind) && durs.length > 0;
    const { L, worst } = animated ? pickLoop(durs) : { L: STEP, worst: 0 };
    const n = animated ? Math.round(L / STEP) : 1;
    const svgPath = path.join(tmp, `${pack}-${kind}.svg`);
    fs.writeFileSync(svgPath, animated ? retime(src, L) : src);
    // Sample two loops in, after every staggered begin (max 0.7 s) has started.
    const t0 = 2 * L;
    for (const scale of [1, 2]) {
      const page = pages[scale];
      await page.goto("file://" + svgPath);
      for (let i = 0; i < n; i++) {
        await page.evaluate((t) => {
          const svg = document.documentElement;
          svg.pauseAnimations();
          svg.setCurrentTime(t);
        }, t0 + (i * L) / n);
        await page.screenshot({
          path: path.join(outDir, `${kind}-${i}${scale === 2 ? "@2x" : ""}.png`),
          omitBackground: true,
          clip: { x: 0, y: 0, width: 32, height: 32 },
        });
      }
    }
    counts[pack][kind] = n;
    if (animated) console.log(`${pack}/${kind}: ${n} frames, loop ${L}s, max speed change ${(worst * 100).toFixed(0)}%`);
  }
}

await browser.close();
fs.rmSync(tmp, { recursive: true, force: true });

const sorted = Object.fromEntries(Object.keys(counts).sort().map((k) => [k, counts[k]]));
fs.writeFileSync(countsFile, `// Generated by gen_frames.mjs — frame counts per pack and cursor kind. Do not edit.
globalThis.LOVESPARK_CURSOR_FRAMES = ${JSON.stringify(sorted, null, 2)};
`);
console.log(`wrote ${Object.keys(sorted).length} packs to cursor_frames.js`);
