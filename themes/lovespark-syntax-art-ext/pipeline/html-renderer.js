/**
 * HTML renderer with CSS classes and span optimization.
 *
 * Generates a self-contained HTML string. Uses CSS classes for token
 * colors instead of inline styles. Consecutive tokens sharing the same
 * class merge into one <span>.
 */

const _HTML_ESCAPE = { '&': '&amp;', '<': '&lt;', '>': '&gt;' };

function _escapeHtml(s) {
  return s.replace(/[&<>]/g, ch => _HTML_ESCAPE[ch]);
}

/**
 * Build CSS class rules for a theme.
 */
function _buildCssClasses(theme) {
  const hexValues = Object.values(theme.tokenColors);
  const rules = [];
  for (let i = 0; i < CSS_CLASSES.length; i++) {
    rules.push(`    .${CSS_CLASSES[i]} { color: ${hexValues[i]} }`);
  }
  return rules.join('\n');
}

/**
 * Render the grid to a self-contained HTML string.
 *
 * @param {Array<Array<{token: string, cssClass: string}>>} grid
 * @param {Object} theme
 * @param {number} fontSize
 * @returns {string} Complete HTML document
 */
function renderHtml(grid, theme, fontSize) {
  const lines = [];

  for (const row of grid) {
    const spans = [];
    let currentClass = null;
    let currentChars = [];

    for (const { token, cssClass } of row) {
      if (cssClass === currentClass) {
        currentChars.push(_escapeHtml(token));
      } else {
        if (currentChars.length > 0) {
          spans.push(`<span class="${currentClass}">${currentChars.join('')}</span>`);
        }
        currentClass = cssClass;
        currentChars = [_escapeHtml(token)];
      }
    }
    // Flush remaining
    if (currentChars.length > 0) {
      spans.push(`<span class="${currentClass}">${currentChars.join('')}</span>`);
    }

    lines.push(spans.join(''));
  }

  const codeBody = lines.join('\n');
  const colorClasses = _buildCssClasses(theme);

  return `<!-- ✨ Generated by LoveSpark Syntax Art -->
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>LoveSpark Syntax Art</title>
  <style>
    body {
      margin: 0;
      padding: 16px;
      background: ${theme.background};
      display: flex;
      justify-content: center;
      align-items: center;
      min-height: 100vh;
    }
    pre {
      font-family: 'Fira Code', 'Consolas', 'Monaco', monospace;
      font-size: ${fontSize}px;
      line-height: 1.0;
      letter-spacing: 0;
      margin: 0;
    }
${colorClasses}
  </style>
</head>
<body>
  <pre>${codeBody}</pre>
</body>
</html>`;
}
